"""Publish composed R5 art (scripts/lastmile-r5/compose.py output) to the runtime.
uv run --no-project --with opencv-python-headless --with numpy python scripts/lastmile-r5/publish.py <composed>
Writes public/scene-art/lastmile-r5/*.webp, src/scenes/lastmile/expandedArtwork.ts and segmentedContours.json.
"""
import json, sys
from pathlib import Path
import cv2
import numpy as np

src = Path(sys.argv[1]); root = Path(__file__).resolve().parents[2]
base = 'scene-art/lastmile-r5'; public = root / 'public' / base; public.mkdir(parents=True, exist_ok=True)
art = json.loads((src / 'expandedArtwork.json').read_text()); anim = json.loads((src / 'animation.json').read_text())
lossless = [cv2.IMWRITE_WEBP_QUALITY, 101]
for name, view in art.items():
    plate = cv2.imread(str(src / f'{name}-base.png')); assert plate.shape[:2] == (view['height'], view['width'])
    assert cv2.imwrite(str(public / f'choice-{name}.webp'), plate, [cv2.IMWRITE_WEBP_QUALITY, 92])
    motion = {}
    for key, box in anim[name].items():
        file = f'{name}-{key.replace("_", "-")}.webp'
        im = cv2.imread(str(src / f'{name}-{key}.png'), cv2.IMREAD_UNCHANGED); assert im.shape[2] == 4
        assert cv2.imwrite(str(public / file), im, lossless if key == 'rotor' else [cv2.IMWRITE_WEBP_QUALITY, 95])
        motion[key.replace('_', '-')] = {**box, 'image': f'{base}/{file}'}
    view['motion'] = motion
(root / 'src/scenes/lastmile/expandedArtwork.ts').write_text(
    '// Generated by scripts/lastmile-r5/publish.py: R5 overscan in logical 1x pixels (Blender layout + gpt paint).\n'
    '// motion: sprites cut from the same paint, boxes in plate pixels (scripts/lastmile-r5/compose.py).\n'
    'export const lastmileChoiceArtwork = ' + json.dumps(art, indent=2) + ';\n')
(root / 'src/scenes/lastmile/segmentedContours.json').write_text((src / 'segmentedContours.json').read_text())
print('R5_PUBLISH_COMPLETE', sorted(p.name for p in public.iterdir()))
